#!/usr/bin/env python3
"""Author the four missing token axes: spacing, typography, elevation, motion —
plus the two density registers (stage, document).

Follows `validation/reports/2026-08-28__token-axes-proposal.md`, which is the plan
(promoted out of gitignored scratch/ on 2026-08-28 so the reasoning survives a clean);
this script is the execution of it. Per-axis provenance, restated here so a
reader doesn't have to open the proposal to know what is transcribed versus
authored:

  SPACING     — TRANSCRIBED verbatim from @carbon/layout 11.58.0's own compiled
                output (`scss/generated/_spacing.scss`, machine-generated by
                Carbon's own build). 13 steps, 0.125rem -> 10rem. Only the DTCG
                `dimension` wrapper is new; the 13 numbers are Carbon's, not
                ours. NOTE: component-index.json's `spacing-scale` component
                was extended from 10 to 13 steps on 2026-08-28 to match. This
                script imports all 13 and FLAGS the mismatch — it does not
                touch component-index.json to resolve it (out of scope).

  TYPOGRAPHY  — MIXED, per brand.md §4 (Anek Latin, OQ-2 resolved 2026-08-27):
      * family   — AUTHORED per brand.md. TWO primitives, because there are two
                    actual typefaces: `sans` (Anek Latin, OQ-2 2026-08-27) and
                    `mono` (Source Code Pro, ART-007, 2026-08-28). Deliberately
                    NO display/body split at this layer — those are roles, and
                    typography.scale.* already expresses them. An earlier pass
                    carried the role down here and produced two leaves holding a
                    byte-identical stack; audit-contracts.py flagged it as a
                    value reachable by two names. Real fallback stacks attached.
      * size     — AUTHORED curated stopping points (7 steps), not Carbon's
                    23-step compiled-formula ramp. brand.md wants one scale at
                    two densities, not a long undifferentiated ramp. Step 07
                    (3.875rem = 62px) is the evidenced display size
                    [ART-005 § Type].
      * weight   — MIXED. light/regular/semibold (300/400/600) are TRANSCRIBED
                    from @carbon/type 11.66.0's compiled `fontWeights` export.
                    heavy (700) and black (800) are AUTHORED — brand.md's
                    evidenced display weight is 700 ("heavy"); Carbon has no
                    value above 600.
      * tracking — AUTHORED, and explicitly a CURVE, not a constant. Only ONE
                    point is evidenced: -0.125rem (-2px) at 62px / step 07
                    [ART-005 § Type]. Every other step is this script's own
                    interpolation (tightens through the scale, crossing to
                    negative around body size rather than Carbon's own table,
                    which stays at 0 tracking until ~92px — see proposal §3).
                    NEEDS VISUAL TESTING before being treated as final; only
                    step 07's value is evidenced.
      * scale    — AUTHORED bundles (composite $type "typography"): one leaf
                    token per named level (display, h1, h2, h3, body, body-sm,
                    caption, code — the exact 8 names component-index.json's
                    `type-scale` component already declares), each a $value
                    object whose four fields are alias strings only, never
                    literals.

  TABULAR FIGURES (brand.md §4, binding) — DTCG has no `font-variant-numeric`
      $type. Mechanism used here, stated explicitly because a rule nothing
      carries is not a rule: every `typography.scale.<level>` leaf token
      carries `$extensions.coforge.fontVariantNumeric: "tabular-nums"`,
      attached to all 8 levels (any of them can carry a number — captions
      label figures, code is often numeric, and "display" covers the stage
      register's "key figures" per brand.md §2). Anything that consumes a
      scale level is expected to read and apply this extension.

  ELEVATION   — geometry AUTHORED, colour ALIASED (not duplicated).
      `semantic.shadow` / `semantic-dark.shadow` already exist and are
      correct; this script does not touch them. The one new primitive
      (`elevation.shadow.raised`) points its `color` field at
      `{semantic.shadow}` and supplies the geometry — Carbon's own numbers
      (2px y-offset, 6px blur, per `@carbon/styles`' hardcoded Sass mixin,
      the only artefact that exists — Carbon ships no DTCG shadow token at
      all) as a STARTING POINT, NOT AN IMPORT (no such token exists upstream
      to import). NEEDS VISUAL CONFIRMATION against the brand's warmer, softer
      language before being treated as final. brand.md §2: a single soft
      shadow, never more than one depth — hence exactly two states (`none`,
      `raised`), no depth ladder. Dark-theme shadow geometry (a parallel
      primitive aliasing `{semantic-dark.shadow}`) is NOT authored here —
      out of scope for this pass.

  MOTION      — TRANSCRIBED verbatim from @carbon/motion 11.51.0's own
                published DTCG (`src/dtcg/motion.json` — this is the one axis
                Carbon ships as native, schema-validated DTCG). Six durations
                (70-700ms), six cubicBezier curves under standard/entrance/exit
                x productive/expressive. At the semantic layer
                (`motion.transition.*`), only the `productive` family is
                aliased, per brand.md §5 ("motion confirms; it does not
                perform"). `expressive` is mirrored into the primitive layer
                (imported, present) but deliberately never aliased into
                anything semantic.

  DENSITY     — AUTHORED per brand.md §2: stage and document "differ in space
                and type scale only, never in colour role or shape language."
                Implemented as two *subsets* pointing at the one shared
                `typography.scale` group and the one shared `spacing` group —
                no duplicated scale, no duplicated spacing ladder. Each
                register's `type-scale` entry uses a non-standard DTCG $type,
                `coforge.levelSet` ($value: an array of pure alias strings) —
                the same kind of documented, structurally-valid, non-spec
                composite Carbon itself uses for its own `transition` $type
                (see proposal §1). It is not a DTCG-standard type; it is
                declared here so nobody mistakes it for one.

THE BINDING CONTRACT
---------------------
Exactly one layer holds literals; everything above it aliases — restated for
every new axis:

    PRIMITIVE (literals allowed)   SEMANTIC (aliases ONLY, recursively —
                                    including inside composite $value dicts
                                    and $value arrays; zero literals, anywhere)
    spacing.*                      (none — spacing has no semantic layer)
    typography.size.*              typography.scale.*
    typography.weight.*
    typography.tracking.*
    typography.family.*
    elevation.shadow.*             elevation.surface.*
    motion.duration.*              motion.transition.*
    motion.easing.*
    (existing) palette.*           (existing) semantic.* / semantic-dark.*
                                    density.*  (aliases spacing.* + typography.scale.*)

A node with `$value` never has non-`$` children (no token nested inside a
token) — the exact defect this repo already found and fixed once in
`semantic-dark` (see flatten-dark-tokens.py). Composite tokens here (the
`typography` and `shadow` $types, and the custom `coforge.levelSet` $type)
avoid this by keeping every sub-field INSIDE the `$value` object/array itself,
never as a sibling JSON key.

SAFETY
------
Refuses to write unless every check passes:
  · zero literals outside primitive groups (walks into composite $value
    dicts/arrays, not just top-level scalars)
  · every alias in the WHOLE file resolves to a real token path (existing
    bare-name palette convention — "{white.default}" meaning
    "palette.white.default" — is preserved for old data; new axes use fully
    qualified paths throughout, exactly as the proposal specifies)
  · no node carries both $value and non-$ children, anywhere in the file
  · existing palette / semantic / semantic-dark are byte-identical to before
  · valid JSON; every leaf token ($value present) has $type

Idempotent: the four axes + density are rebuilt deterministically from this
script's own fixed source data every run, then assigned wholesale onto the
document — running it twice produces byte-identical output both times.

    python3 validation/build-token-axes.py            # check only, writes nothing
    python3 validation/build-token-axes.py --apply    # verify, then write
"""
