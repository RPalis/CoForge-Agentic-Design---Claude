def dim(value, unit="rem"):
    return {"value": value, "unit": unit}


def build_spacing():
    """13 steps, transcribed verbatim from @carbon/layout 11.58.0
    scss/generated/_spacing.scss (Carbon's own machine-generated build
    output). component-index.json's spacing-scale was extended to 13 to match,
    2026-08-28 — the contract is now exact."""
    steps = [
        ("01", 0.125), ("02", 0.25), ("03", 0.5), ("04", 0.75), ("05", 1),
        ("06", 1.5), ("07", 2), ("08", 2.5), ("09", 3), ("10", 4),
        ("11", 5), ("12", 6), ("13", 10),
    ]
    out = {
        "$extensions": {"coforge": {"complete_scale":
            "A complete imported ladder. A layout consumes steps directly by name, so "
            "most steps are never aliased by a semantic token and that is the scale "
            "working as intended — unlike colour, spacing has no role layer between the "
            "primitive and the surface."}},
        "$description": "Structural spacing scale. Transcribed from @carbon/layout "
                         "11.58.0 (Apache-2.0) — no brand signal opposes a different "
                         "cadence (token-axes-proposal.md §2). 13 steps; "
                         "component-index.json's spacing-scale component currently "
                         "was extended to 13 on 2026-08-28; the contract is exact. "
                         "script imports faithfully and flags, not resolves.",
    }
    for key, rem in steps:
        out[key] = {
            "$type": "dimension",
            "$value": dim(rem),
            "$description": f"Carbon spacing-{key} — {rem}rem.",
            "$extensions": {"coforge": {"source": "@carbon/layout@11.58.0", "transcribed": True}},
        }
    return out


