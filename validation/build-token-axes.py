def main():
    apply = "--apply" in sys.argv
    original = json.load(open(TOKENS))

    preserved_before = {g: copy.deepcopy(original[g]) for g in PRESERVE_GROUPS}

    candidate = dict(original)
    candidate["spacing"] = build_spacing()
    candidate["typography"] = build_typography()
    candidate["elevation"] = build_elevation()
    candidate["motion"] = build_motion()
    candidate["density"] = build_density()

    ok = True

    # 1. zero literals outside primitive groups
    leaks = find_literal_leaks(candidate)
    if leaks:
        print(f"  FAIL {len(leaks)} literal(s) outside primitive groups")
        for p, v in leaks[:10]:
            print(f"      {p} -> {v!r}")
        ok = False
    else:
        print("  zero literals outside primitive groups")

    # 2. every alias resolves
    bad = find_unresolved_aliases(candidate)
    if bad:
        print(f"  FAIL {len(bad)} unresolved alias(es)")
        for p, v in bad[:10]:
            print(f"      {p} -> {v}")
        ok = False
    else:
        print("  every alias resolves")

    # 3. no node carries both $value and non-$ children
    hyb = hybrids(candidate)
    if hyb:
        print(f"  FAIL {len(hyb)} hybrid node(s) (token nested inside a token)")
        for p in hyb[:10]:
            print(f"      {p}")
        ok = False
    else:
        print("  no node carries both $value and child tokens")

    # 4. palette/semantic/semantic-dark byte-identical
    preserve_ok = True
    for g in PRESERVE_GROUPS:
        if candidate[g] != preserved_before[g]:
            print(f"  FAIL {g} was modified")
            preserve_ok = False
    if preserve_ok:
        print(f"  {', '.join(PRESERVE_GROUPS)} unchanged")
    else:
        ok = False

    # 5. every leaf has $type (valid JSON is implicit — we built it as a dict)
    missing = find_missing_type(candidate)
    if missing:
        print(f"  FAIL {len(missing)} leaf(ves) missing $type")
        for p in missing[:10]:
            print(f"      {p}")
        ok = False
    else:
        print("  every leaf token has $type and $value")

    # counts + flags, informational
    n_leaves_before = len(all_leaves(original))
    n_leaves_after = len(all_leaves(candidate))
    print(f"\n  leaves before: {n_leaves_before}  after: {n_leaves_after}  "
          f"(+{n_leaves_after - n_leaves_before})")
    print("  NOTE: spacing imports all 13 Carbon steps; component-index.json's "
          "spacing-scale was extended to 13 on 2026-08-28 — contract now exact.")
    print("  FLAG: typography.tracking steps 01-06 and elevation.shadow.raised's "
          "geometry are authored/starting-point values needing visual testing — "
          "only tracking step 07 (-0.125rem @ 62px) is evidenced.")

    if not ok:
        print("\n  REFUSING TO WRITE")
        return 1

    if not apply:
        print(f"\n  check only — would add spacing, typography, elevation, motion, "
              f"density ({n_leaves_after - n_leaves_before} new leaves). "
              f"Re-run with --apply")
        return 0

    with open(TOKENS, "w") as fh:
        json.dump(candidate, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(f"\n  WROTE {os.path.relpath(TOKENS, ROOT)} — "
          f"{n_leaves_after - n_leaves_before} new leaves across 4 axes + density")
    return 0


if __name__ == "__main__":
    sys.exit(main())
